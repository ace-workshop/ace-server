#[cfg(test)]
mod tests {
    use super::*;
    use sha2::{Digest, Sha256};
    #[test]
    fn digests_match_canonical_bytes() {
        fn check<T: Schema>() {
            assert_eq!(
                Sha256::digest(T::CANONICAL.as_bytes())[..],
                T::DIGEST,
                "{}",
                T::CANONICAL
            );
        }
        check::<Transport>();
        check::<Connection>();
        check::<Bind>();
        check::<Kick>();
        check::<SendToSession>();
        check::<Online>();
        check::<OnlineCount>();
        check::<Ack>();
    }
}
